/**
 * Copies the legal and policy documents from the website
 * (../frontend/src/legal) into the app (src/legal/documents.generated.ts),
 * so both show exactly the same text and agree on which versions a
 * school confirmed. Run after changing any document on the website:
 *
 *   npm run sync-legal
 */
const fs = require('fs');
const path = require('path');

const webLegal = path.join(__dirname, '..', '..', 'frontend', 'src', 'legal');
const list = fs.readFileSync(path.join(webLegal, 'documents.ts'), 'utf8');
const entry = /\{\s*slug:\s*'([^']+)',\s*group:\s*'([^']+)',(\s*forSchools:\s*false,)?\s*title:\s*'([^']+)'/g;
const documents = [];
let match;
while ((match = entry.exec(list))) {
  const [, slug, group, notForSchools, title] = match;
  if (notForSchools) continue; // e.g. the Data Processing Agreement, a template to sign
  const file = path.join(webLegal, `${slug}.md`);
  documents.push({ slug, group, title, source: fs.readFileSync(file, 'utf8') });
}
if (documents.length === 0) throw new Error(`No documents found in ${webLegal}/documents.ts`);

const out = path.join(__dirname, '..', 'src', 'legal', 'documents.generated.ts');
fs.writeFileSync(out, `// Generated by scripts/sync-legal.js from the website's documents. Do not edit by hand.
export const GENERATED_DOCUMENTS: { slug: string; group: 'legal' | 'trust'; title: string; source: string }[] = ${JSON.stringify(documents, null, 2)};
`);
console.log(`Wrote ${documents.length} documents to ${path.relative(process.cwd(), out)}`);
